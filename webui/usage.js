/*
 * Usage widget (token/AIU consumption) - see ../usage_index.py for the data
 * model. Pieces:
 *   - #health-usage  : today / 7d / 30d AIU across ALL sessions; hover = daily
 *                      chart, cost-weighted token-type donut, top sessions.
 *   - #health-quota  : premium_interactions quota (unit unverified -> tooltip).
 *   - thread header  : decorateThreadMeta() appends "N AIU", 🧠 context and
 *                      ♨ cache chips to #thread-meta for the OPEN session.
 *   - sidebar        : window.usageWidget.aiuHtml(session) suffix (app.js).
 * Data: GET /api/usage?conversation_id=..., polled every 60 s and re-fetched
 * (throttled) when the open session changes. USAGE_WIDGET=off hides it all.
 */
(function () {
  const POLL_MS = 60000;
  const THROTTLE_MS = 30000;
  const HEAVY = 5000;
  let data = null;
  let fetchedFor = null;
  let fetchedAt = 0;
  let inflight = false;
  let lastSession = null;
  let range = '1';

  const esc = (s) => String(s == null ? '' : s).replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
  const fmtAiu = (n) => (n == null ? '—' : n >= 1000 ? `${(n / 1000).toFixed(n >= 100000 ? 0 : 1)}k` : String(Math.round(n)));
  const fmtTok = (n) => (n == null ? '—' : n >= 1e6 ? `${(n / 1e6).toFixed(1)}M` : n >= 1000 ? `${(n / 1000).toFixed(1).replace(/\.0$/, '')}k` : String(n));
  const ICO = (e) => `<span class="uw-ico">${e}</span>`;

  const TIPS = {
    cache_read: 'Prompt tokens served from the provider cache (the already-seen conversation prefix). Cheapest: ~20 AIU per M tokens. Most of each request is this.',
    input: 'Fresh, uncached prompt tokens sent this request (new user text, new tool results). ~200 AIU per M tokens.',
    cache_write: 'Tokens written into the cache for the first time (new prefix part, or the whole prefix after the 5-min TTL expired = cold wake). ~250 AIU per M tokens.',
    output: 'Tokens generated by the model (answers, tool calls, reasoning). Most expensive: ~1000 AIU per M tokens.',
  };
  const COLORS = { cache_read: '#4a9eff', input: '#ecb22e', cache_write: '#2eb67d', output: '#e01e5a' };

  function donut(split, extraLegend) {
    let acc = 0;
    const stops = split.map((s) => { const a = acc; acc += s.pct; return `${COLORS[s.type] || '#888'} ${a}% ${acc}%`; });
    const legend = split.map((s) => `<span><i class="uw-sw" style="background:${COLORS[s.type] || '#888'}"></i><u class="uw-tip" data-tip="${esc(TIPS[s.type] || '')}">${esc(s.type)}</u> ≈ ${s.pct}%</span>`).join('');
    return `<div class="uw-row"><div class="uw-donut" style="background:conic-gradient(${stops.join(',')})"></div><div class="uw-leg">${legend}${extraLegend || ''}</div></div>`;
  }

  const RANGE_LABEL = { '1': 'today', '7': 'last 7 days', '30': 'last 30 days' };

  function usagePopover(d) {
    const r = d.ranges[range] || d.ranges['1'];
    const max = Math.max(1, ...r.series.map((x) => x.aiu));
    const lastIdx = r.unit === 'hour' ? new Date().getHours() : r.series.length - 1;
    const chart = r.series.map((x, i) => `<i class="${i === lastIdx ? 'uw-today' : ''}" style="height:${(x.aiu / max) * 100}%" title="${esc(x.day)}: ${x.aiu} AIU"></i>`).join('');
    const top = r.top.map((t) => {
      const title = esc(t.title);
      const name = t.conversation_id ? `<a href="#open=${esc(t.conversation_id)}">${title}</a>` : title;
      return `<tr><td>${name}</td><td>${Math.round(t.aiu).toLocaleString()}</td><td>${esc(t.kind)}</td></tr>`;
    }).join('') || '<tr><td colspan="3" class="uw-muted">no usage in this range</td></tr>';
    const tabs = ['1', '7', '30'].map((k) => `<button type="button" class="uw-range-btn${k === range ? ' uw-active' : ''}" data-range="${k}">${k}d</button>`).join('');
    return `<div class="uw-tabs">${tabs}</div>`
      + `<h4>AIU per ${r.unit}, ${RANGE_LABEL[range]} (all ${d.sessions_count} sessions)</h4><div class="uw-chart">${chart}</div>`
      + donut(r.token_split || d.token_split, `<small class="uw-muted">cost-weighted, ${RANGE_LABEL[range]}; estimate: each session's token mix applied to its AIU in range</small>`)
      + `<h4 style="margin-top:10px">Top sessions (${RANGE_LABEL[range]}, AIU)</h4><table><tr><th>session</th><th>AIU</th><th>kind</th></tr>${top}</table>`
      + `<div class="uw-muted">Burn 7d avg <b style="color:var(--slack-text-primary)">${fmtAiu(d.burn.avg7)}/day</b> · 30d avg <b style="color:var(--slack-text-primary)">${fmtAiu(d.burn.avg30)}/day</b> · 30d projection at the 7d rate ≈ <b style="color:var(--slack-text-primary)">${fmtAiu(d.burn.projection30)}</b></div>`;
  }

  document.addEventListener('click', (e) => {
    const btn = e.target.closest && e.target.closest('.uw-range-btn');
    if (!btn) return;
    e.preventDefault();
    range = btn.dataset.range;
    renderStrip();
  });

  document.addEventListener('click', (e) => {
    const a = e.target.closest && e.target.closest('.uw-quota-refresh');
    if (!a) return;
    e.preventDefault();
    a.textContent = 'refreshing…';
    fetchUsage(lastSession ? lastSession.conversation_id : null, true);
  });

  function quotaView(q) {
    if (!q) return null;
    if (q.unlimited) return { text: 'unlimited', cls: '', html: '<h4>premium_interactions quota</h4>Unlimited entitlement.' };
    const pct = q.used_pct == null ? 0 : q.used_pct;
    const cls = pct >= 95 ? 'uw-quota-crit' : pct >= 80 ? 'uw-quota-hi' : '';
    const reset = q.reset_at ? new Date(q.reset_at) : null;
    const ms = reset ? reset - Date.now() : null;
    const days = ms == null ? null : Math.floor(ms / 86400000);
    const hrs = ms == null ? null : Math.floor((ms % 86400000) / 3600000);
    const resetTxt = ms == null ? '' : ms <= 0 ? ' · ⟳ resetting' : days >= 1 ? ` · ⟳ resets in ${days}d${hrs ? ` ${hrs}h` : ''}` : ` · ⟳ resets in ${Math.max(1, hrs)}h`;
    const resetFull = reset ? reset.toLocaleString([], { dateStyle: 'medium', timeStyle: 'short' }) : '—';
    const ageMin = q.fetched_at ? Math.max(0, Math.round((Date.now() / 1000 - q.fetched_at) / 60)) : null;
    const ageTxt = ageMin == null ? '' : ageMin < 1 ? 'updated just now' : ageMin < 120 ? `updated ${ageMin} min ago` : `updated ${Math.round(ageMin / 60)} h ago`;
    const stale = q.fetched_at && (Date.now() / 1000 - q.fetched_at) > 2 * (q.ttl_seconds || 3600);
    return {
      text: `${fmtAiu(q.used)} / ${fmtAiu(q.entitlement)}${q.remaining_pct != null ? ` · ${Math.round(q.remaining_pct)}% left` : ''}${resetTxt}`,
      cls: stale ? `${cls} uw-muted` : cls,
      html: `<h4>premium_interactions quota</h4><div class="uw-bar"><i style="width:${Math.min(100, pct)}%"></i></div>`
        + `Used ${q.used.toLocaleString()} of ${q.entitlement.toLocaleString()} · overage ${q.overage}<br><span class="uw-quota-reset">Resets: ${esc(resetFull)} (local)</span><br>`
        + (reset ? '' : '<span class="uw-quota-noreset">Reset date unavailable (fallback source).</span><br>')
        + `<span class="uw-quota-age">${esc(ageTxt)}${q.error ? ` — last refresh failed: ${esc(q.error)}` : ''} · <a href="#" class="uw-quota-refresh">refresh now</a>${q.refresh_limited ? ' <i class="uw-muted">(just refreshed — try again in 30 s)</i>' : ''}</span><br>`
        + `<small class="uw-muted">Colour rule: neutral &lt; 80% used, soft amber from 80%, soft red from 95%.<br>ⓘ unit (AIU vs premium requests) unverified — source: ${esc(q.source || 'account.getQuota')}, refreshed hourly.</small>`,
      title: reset ? `Quota resets ${resetFull} (local time)` : '',
    };
  }

  function renderStrip() {
    const usageEl = document.getElementById('health-usage');
    const quotaEl = document.getElementById('health-quota');
    if (!usageEl || !quotaEl) return;
    if (!data || !data.enabled) { usageEl.style.display = 'none'; quotaEl.style.display = 'none'; return; }
    if (data.indexing) {
      usageEl.style.display = '';
      usageEl.innerHTML = `${ICO('⚡')} <span class="uw-muted">usage: indexing…</span>`;
      quotaEl.style.display = 'none';
      return;
    }
    usageEl.style.display = '';
    usageEl.innerHTML = `${ICO('⚡')} today <b>${fmtAiu(data.totals.today)}</b> · 7d <b>${fmtAiu(data.totals.d7)}</b> · 30d <b>${fmtAiu(data.totals.d30)}</b> AIU<div class="uw-pop">${usagePopover(data)}</div>`;
    const q = quotaView(data.quota);
    if (!q) { quotaEl.style.display = 'none'; return; }
    quotaEl.style.display = '';
    quotaEl.innerHTML = `${ICO('🎯')} <b class="${q.cls}">${esc(q.text)}</b><div class="uw-pop uw-sm">${q.html}</div>`;
  }

  function ctxPopover(sd, title) {
    const c = sd.context;
    const parts = [['system', c.systemTokens, '#4a9eff'], ['tool defs', c.toolDefinitionsTokens, '#ecb22e'], ['conversation', c.conversationTokens, '#2eb67d']].filter((p) => p[1] != null);
    const sum = parts.reduce((a, p) => a + p[1], 0) || 1;
    let acc = 0;
    const stops = parts.map((p) => { const a = acc; acc += (p[1] / sum) * 100; return `${p[2]} ${a}% ${acc}%`; });
    const legend = parts.map((p) => `<span><i class="uw-sw" style="background:${p[2]}"></i>${p[0]} ${fmtTok(p[1])} (${Math.round((p[1] / sum) * 100)}%)</span>`).join('');
    const limit = c.tokenLimit || 200000;
    return `<h4 class="uw-nocaps" title="${esc(title)}">Selected session: ${esc(title)}</h4>`
      + (parts.length ? `<div class="uw-row"><div class="uw-donut" style="background:conic-gradient(${stops.join(',')})"></div><div class="uw-leg">${legend}<b>total ${fmtTok(c.currentTokens)} / ${fmtTok(limit)}</b></div></div>` : '')
      + `<div class="uw-bar"><i style="width:${Math.min(100, (c.currentTokens / limit) * 100)}%"></i></div>`
      + `Session AIU: <b>${sd.aiu == null ? '—' : sd.aiu}</b><br><small class="uw-muted">context source: ${c.source === 'live' ? 'live SDK event' : 'last session shutdown'}</small>`;
  }

  let cacheEl = null;
  let cacheExpires = null;
  function tickCache() {
    if (!cacheEl || !cacheEl.isConnected) return;
    const s = cacheExpires ? Math.max(0, Math.round((cacheExpires - Date.now()) / 1000)) : 0;
    const ico = cacheEl.querySelector('.uw-cache-ico');
    const cd = cacheEl.querySelector('.uw-cache-cd');
    if (ico) ico.textContent = s ? '♨' : '❄';
    if (cd) cd.textContent = s ? `${Math.floor(s / 60)}:${String(s % 60).padStart(2, '0')}` : 'cold';
  }
  setInterval(tickCache, 1000);

  // Appends AIU + context + cache chips to the (already textual) #thread-meta.
  function decorateThreadMeta(metaEl, session) {
    lastSession = session;
    cacheEl = null;
    if (data && (!data.enabled || data.indexing === true && session.aiu == null)) return;
    maybeFetch(session);
    const sd = data && data.session && fetchedFor === session.conversation_id ? data.session : null;
    const sep = '<span class="uw-sep">·</span>';
    let html = '';
    const aiu = session.aiu != null ? session.aiu : (sd ? sd.aiu : null);
    if (aiu != null) html += `${sep}<span title="AIU spent by this session (all time)">${fmtAiu(aiu)} AIU</span>`;
    if (!sd) {
      if (html) { const w = document.createElement('span'); w.innerHTML = html; metaEl.appendChild(w); }
      return;
    }
    if (sd.context && sd.context.currentTokens != null) {
      html += `${sep}<span class="uw-hov" title="">${ICO('🧠')} ${fmtTok(sd.context.currentTokens)}/${fmtTok(sd.context.tokenLimit || 200000)}<div class="uw-pop uw-sm uw-right">${ctxPopover(sd, (document.getElementById('thread-title') || {}).textContent || session.title || '')}</div></span>`;
    }
    if (sd.cache && sd.cache.expires_at) {
      cacheExpires = Date.parse(sd.cache.expires_at);
      html += `${sep}<span class="uw-hov uw-cache" title="">${ICO('<span class="uw-cache-ico">♨</span>')} <span class="uw-cache-cd">—</span><div class="uw-pop uw-sm uw-right"><h4 class="uw-nocaps">Prompt cache (selected session)</h4>TTL ${sd.cache.ttl_seconds || 300} s, expires at ${esc(new Date(cacheExpires).toLocaleTimeString())}.<br>Cold wake ≈ 48 AIU vs warm ≈ 24.5 AIU.</div></span>`;
    }
    if (!html) return;
    const wrap = document.createElement('span');
    wrap.className = 'uw-thread-extra';
    wrap.innerHTML = html;
    metaEl.appendChild(wrap);
    cacheEl = wrap.querySelector('.uw-cache');
    tickCache();
  }

  async function fetchUsage(conversationId, force) {
    if (inflight) return;
    inflight = true;
    try {
      const params = [];
      if (conversationId) params.push(`conversation_id=${encodeURIComponent(conversationId)}`);
      if (force) params.push('refresh=1');
      const qs = params.length ? `?${params.join('&')}` : '';
      const d = await api(`/api/usage${qs}`);
      if (d.session) d.session.conversation_id = conversationId;
      data = d;
      fetchedFor = conversationId || null;
      fetchedAt = Date.now();
      renderStrip();
      if (lastSession && typeof updateThreadMeta === 'function' && conversationId === lastSession.conversation_id) updateThreadMeta(lastSession);
    } catch (e) {
      console.error('usage fetch failed', e);
    } finally {
      inflight = false;
    }
  }

  function maybeFetch(session) {
    const id = session ? session.conversation_id : null;
    if (inflight) return;
    if (id !== fetchedFor || Date.now() - fetchedAt > THROTTLE_MS) fetchUsage(id);
  }

  function aiuHtml(s) {
    if (s.aiu == null || (data && !data.enabled)) return '';
    const heavy = s.aiu > HEAVY;
    return ` · <span class="${heavy ? 'uw-heavy' : ''}" title="AIU spent by this session (all time)${heavy ? ` — heavy: above ${HEAVY} AIU` : ''}">${fmtAiu(s.aiu)} AIU</span>`;
  }

  setInterval(() => fetchUsage(lastSession ? lastSession.conversation_id : null), POLL_MS);
  window.addEventListener('load', () => fetchUsage(null));
  window.usageWidget = { decorateThreadMeta, aiuHtml, refresh: () => fetchUsage(lastSession ? lastSession.conversation_id : null) };
})();
